"""
extract_notes.py
Generated by Claude
从 Google Play Books 导出的 .docx 笔记文件中提取所有高亮/笔记，
并在 _posts 下生成对应的 "年-月-日-书名.md"。

用法:
    python "Extract notes.py"

    取下载文件夹里最新的 'Notes from *.docx'；笔记数与文档声明一致（没有缺失）
    且 _posts 里还没有这本书的 md 时，按今天日期新建一个。
    已有同名书的 md 则不动（里面的 #### 摘要是人工整理的）。

依赖:
    pip install python-docx
"""

import os
import re
import sys
from datetime import date
from pathlib import Path
from docx import Document
from docx.oxml.ns import qn

os.system('')   # 让 Windows 控制台识别 ANSI 颜色码


def green(msg: str) -> str:
    return f"\033[92m{msg}\033[0m"


def red(msg: str) -> str:
    return f"\033[91m{msg}\033[0m"


def yellow(msg: str) -> str:
    return f"\033[93m{msg}\033[0m"


def find_latest_notes_docx(folder: str) -> Path:
    """Find the most recently modified 'Notes from *.docx' file in folder.

    Play Books 的导出文件名有两种形式（书名两侧带/不带下划线）：
        Notes from _书名_.docx
        Notes from 书名.docx
    """
    candidates = [
        p for p in Path(folder).glob("Notes from *.docx")
        if not p.name.startswith('~$')          # 跳过 Word 临时锁文件
    ]
    if not candidates:
        raise FileNotFoundError(
            f"No 'Notes from *.docx' file found in {folder}"
        )
    return max(candidates, key=lambda p: p.stat().st_mtime)


def get_tc_texts(tbl_el) -> list[str]:
    """返回表格所有 tc 的文本列表（含空字符串）。"""
    return [
        ''.join(e.text or '' for e in tc.iter(qn('w:t')))
        for tc in tbl_el.iter(qn('w:tc'))
    ]


def book_title_from(docx_path: Path) -> str:
    """从 'Notes from _书名_.docx' / 'Notes from 书名.docx' 里取出书名。

    Play Books 会把书名里的冒号等字符换成下划线，这里一并去掉。
    """
    m = re.fullmatch(r'Notes from (.*)', docx_path.stem)
    title = m.group(1) if m else docx_path.stem
    return ' '.join(title.replace('_', ' ').split())


def find_existing_post(posts_folder: Path, title: str) -> Path | None:
    """在 _posts（含子文件夹）里找 '年-月-日-书名.md'（日期不限），找不到返回 None。"""
    for p in posts_folder.rglob('*.md'):
        m = re.fullmatch(r'\d{4}-\d{1,2}-\d{1,2}-(.*)', p.stem)
        if m and m.group(1).strip().lower() == title.lower():
            return p
    return None


def build_post(title: str, notes: list[dict]) -> str:
    """front matter + <!-- more --> + 笔记正文（每条之间空一行）。"""
    front_matter = (
        "---\n"
        "layout: post\n"
        f"title:  {title}\n"
        "categories: [Books, ]\n"
        "tags: []\n"
        "---\n"
        "\n"
        "<!-- more -->\n"
    )
    return front_matter + '\n\n'.join(note['text'] for note in notes) + '\n'


def extract_notes(docx_path: str) -> tuple[list[dict], bool]:
    """
    解析 docx，返回 (笔记列表, 是否完整)。
    “完整”指解析出的条数与 Play Books 在文件头声明的条数一致。
    每条笔记是一个 dict:
        {
            "chapter": str,   # 所属章节
            "text":    str,   # 高亮/笔记正文
            "date":    str,   # 标注日期（如 "2026年3月12日"）
            "page":    str,   # 页码（可能为空）
        }

    Play Books 导出格式说明
    -----------------------
    每条笔记对应一个独立的 <w:tbl>，内含 4 个 <w:tc>：
        tc[0]  正文 + 日期 + 页码（含超链接格式）
        tc[1]  空
        tc[2]  正文 + 日期（纯文本，无页码）
        tc[3]  页码（纯数字字符串）
    章节标题以 Heading1 / Heading2 段落形式穿插在表格之间。
    """
    doc = Document(docx_path)
    body = doc.element.body

    date_pattern = re.compile(r'(\d{4}年\d{1,2}月\d{1,2}日|[A-Z][a-z]+ \d{1,2}, \d{4})$')

    # Play Books 的导出把同一批笔记写了两遍，分在两个区块：
    #     "Annotations by color"  —— 按高亮颜色分组，章节只有颜色名（Yellow）
    #     "All your annotations"  —— 按书中章节分组，信息完整
    # 两边都收会正好翻倍（实测 53 条 -> 106 条）。只取后者；
    # 导出变体里若没有后者，则退回到“全收”。
    SECTION_ALL = 'All your annotations'
    SECTION_BY_COLOR = 'Annotations by color'

    def heading_texts():
        out = []
        for ch in body:
            if ch.tag.split('}')[-1] != 'p':
                continue
            st = ch.find('.//' + qn('w:pStyle'))
            if st is None or 'Heading' not in st.get(qn('w:val'), ''):
                continue
            out.append(''.join(e.text or '' for e in ch.iter(qn('w:t'))).strip())
        return out

    collecting = SECTION_ALL not in heading_texts()

    notes = []
    current_chapter = ""
    claimed_count = None   # Play Books 在文件头写的 "N notes/highlights"

    for child in body:
        tag = child.tag.split('}')[-1]

        # ── 段落：捕获章节标题 ──────────────────────────────────────────────
        if tag == 'p':
            style_el = child.find('.//' + qn('w:pStyle'))
            style = style_el.get(qn('w:val'), '') if style_el is not None else ''
            text = ''.join(e.text or '' for e in child.iter(qn('w:t'))).strip()

            if 'Heading' in style and text:
                # 区块开关：只在 "All your annotations" 里收笔记
                if text == SECTION_ALL:
                    collecting = True
                    continue
                if text == SECTION_BY_COLOR:
                    collecting = False
                    current_chapter = ""
                    continue

                # 过滤掉文件顶部的固定标题
                m_count = re.match(r'^(\d+)\s*notes', text)
                if m_count:
                    claimed_count = int(m_count.group(1))
                elif collecting:
                    current_chapter = text

        # ── 表格：提取笔记 ─────────────────────────────────────────────────
        elif tag == 'tbl':
            if not collecting:
                continue

            tcs = get_tc_texts(child)

            if not tcs:
                continue

            # Play Books 格式：tc[2] = 正文+日期，tc[3] = 页码
            # 兼容格式变体（tc 数量不足 3 的情况）
            if len(tcs) >= 3:
                raw_text = tcs[2].strip()
                page = tcs[3].strip() if len(tcs) >= 4 else ""
            else:
                raw_text = tcs[0].strip()
                page = ""

            # 必须含日期才算笔记
            m = date_pattern.search(raw_text)
            if not m:
                continue

            date = m.group(1)
            note_text = raw_text[:m.start()].strip()

            if note_text:
                notes.append({
                    "chapter": current_chapter,
                    "text":    note_text,
                    "date":    date,
                    "page":    page,
                })

    # ── 自检：与 Play Books 声明的笔记数对比 ──────────────────────────────
    complete = claimed_count is None or claimed_count == len(notes)

    if claimed_count is None:
        print(yellow(f"NOTE: 文档里没找到声明的笔记数，无法核对，解析出 {len(notes)} 条。"))
    elif not complete:
        print(red(
            f"WARNING: 文档声明 {claimed_count} 条，实际解析出 {len(notes)} 条 —— "
            f"若正好是声明数的整数倍，说明两个区块都被收了；"
            f"否则是解析遗漏，请检查格式变体。"
        ))
    else:
        print(green(f"OK: {len(notes)}/{claimed_count} 条，与文档声明一致。"))
        print(
            "  提示：若这个数字比你在 Play Books 里的实际笔记少，说明 Drive 上的 "
            "docx 是旧快照 —— 先让 Play Books 同步一次，再重新下载。"
        )

    return notes, complete


if __name__ == '__main__':
    # ── 在这里修改输入文件夹/输出文件夹 ────────────────────────────────────
    INPUT_FOLDER = r"C:\Users\reala\Downloads"
    POSTS_FOLDER = Path(__file__).resolve().parent      # 本脚本所在的 _posts
    # ──────────────────────────────────────────────────────────────────────

    try:
        input_file = find_latest_notes_docx(INPUT_FOLDER)
    except FileNotFoundError as e:
        print(red(f"FAIL: {e}"))
        sys.exit(1)
    title = book_title_from(input_file)
    print(f"Latest notes file: {input_file.name}")
    print(f"Book title: {title}\n")

    notes, complete = extract_notes(str(input_file))

    existing = find_existing_post(POSTS_FOLDER, title)
    if not notes:
        print(red("FAIL: 没有解析出任何笔记，不生成 md。"))
    elif not complete:
        print(red("FAIL: 笔记有缺失，不生成 md。"))
    elif existing:
        print(yellow(f"SKIP: 已存在 {existing.name}，不覆盖。"))
    else:
        today = date.today()
        post = POSTS_FOLDER / f"{today.year}-{today.month}-{today.day}-{title}.md"
        post.write_text(build_post(title, notes), encoding='utf-8')
        print(green(f"Done: saved to {post.name} ({len(notes)} notes)"))
